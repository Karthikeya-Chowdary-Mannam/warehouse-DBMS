-- Warehouse Management System — PostgreSQL schema.
-- Run with: psql "$DATABASE_URL" -f schema.sql

CREATE TABLE IF NOT EXISTS manager (
    manager_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    phone TEXT NOT NULL,
    password_hash TEXT NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS warehouse (
    warehouse_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    manager_id BIGINT NOT NULL REFERENCES manager(manager_id),
    name TEXT NOT NULL,
    location TEXT NOT NULL,
    capacity NUMERIC(14,2) NOT NULL CHECK (capacity >= 0),
    UNIQUE (manager_id, name)
);

CREATE TABLE IF NOT EXISTS employee (
    employee_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    warehouse_id BIGINT NOT NULL REFERENCES warehouse(warehouse_id),
    name TEXT NOT NULL,
    designation TEXT NOT NULL,
    phone TEXT NOT NULL,
    hire_date DATE NOT NULL DEFAULT CURRENT_DATE
);

CREATE TABLE IF NOT EXISTS users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL UNIQUE REFERENCES employee(employee_id),
    username TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS supplier (
    supplier_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL CONSTRAINT uq_supplier_name UNIQUE,
    contact_person TEXT NOT NULL,
    phone TEXT NOT NULL,
    email TEXT NOT NULL,
    address TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS customer (
    customer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL CONSTRAINT uq_customer_name UNIQUE,
    phone TEXT NOT NULL,
    email TEXT NOT NULL,
    address TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS product_category (
    category_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name TEXT NOT NULL UNIQUE,
    description TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS product (
    product_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT NOT NULL REFERENCES product_category(category_id),
    product_name TEXT NOT NULL CONSTRAINT uq_product_name UNIQUE,
    unit_price NUMERIC(12,2) NOT NULL CHECK (unit_price >= 0),
    unit_of_measure TEXT NOT NULL DEFAULT 'unit',
    reorder_level INTEGER NOT NULL DEFAULT 0 CHECK (reorder_level >= 0)
);

CREATE TABLE IF NOT EXISTS inventory (
    warehouse_id BIGINT NOT NULL REFERENCES warehouse(warehouse_id),
    product_id BIGINT NOT NULL REFERENCES product(product_id),
    quantity_on_hand INTEGER NOT NULL DEFAULT 0 CHECK (quantity_on_hand >= 0),
    last_updated TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (warehouse_id, product_id)
);

CREATE TABLE IF NOT EXISTS purchase_order (
    po_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id BIGINT NOT NULL REFERENCES supplier(supplier_id),
    warehouse_id BIGINT NOT NULL REFERENCES warehouse(warehouse_id),
    employee_id BIGINT NOT NULL REFERENCES employee(employee_id),
    order_date DATE NOT NULL DEFAULT CURRENT_DATE,
    status TEXT NOT NULL DEFAULT 'Draft'
        CHECK (status IN ('Draft','Placed','Partially Received','Received','Cancelled')),
    total_amount NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (total_amount >= 0)
);

CREATE TABLE IF NOT EXISTS purchase_order_item (
    po_id BIGINT NOT NULL REFERENCES purchase_order(po_id) ON DELETE CASCADE,
    product_id BIGINT NOT NULL REFERENCES product(product_id),
    quantity_ordered INTEGER NOT NULL CHECK (quantity_ordered > 0),
    unit_cost NUMERIC(12,2) NOT NULL CHECK (unit_cost >= 0),
    PRIMARY KEY (po_id, product_id)
);

CREATE TABLE IF NOT EXISTS sales_order (
    so_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES customer(customer_id),
    warehouse_id BIGINT NOT NULL REFERENCES warehouse(warehouse_id),
    employee_id BIGINT NOT NULL REFERENCES employee(employee_id),
    order_date DATE NOT NULL DEFAULT CURRENT_DATE,
    status TEXT NOT NULL DEFAULT 'Pending'
        CHECK (status IN ('Pending','Processing','Shipped','Delivered','Cancelled','Returned')),
    total_amount NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (total_amount >= 0)
);

CREATE TABLE IF NOT EXISTS sales_order_item (
    so_id BIGINT NOT NULL REFERENCES sales_order(so_id) ON DELETE CASCADE,
    product_id BIGINT NOT NULL REFERENCES product(product_id),
    quantity_ordered INTEGER NOT NULL CHECK (quantity_ordered > 0),
    unit_price NUMERIC(12,2) NOT NULL CHECK (unit_price >= 0),
    PRIMARY KEY (so_id, product_id)
);

CREATE TABLE IF NOT EXISTS delivery (
    delivery_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    so_id BIGINT NOT NULL UNIQUE REFERENCES sales_order(so_id),
    delivery_date DATE NOT NULL,
    delivery_address TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'Preparing'
        CHECK (status IN ('Preparing','Dispatched','In Transit','Delivered','Failed','Returned')),
    carrier_name TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS payment (
    payment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    so_id BIGINT NOT NULL REFERENCES sales_order(so_id),
    payment_date DATE NOT NULL DEFAULT CURRENT_DATE,
    amount NUMERIC(14,2) NOT NULL CHECK (amount >= 0),
    payment_method TEXT NOT NULL
        CHECK (payment_method IN ('Cash','Card','Bank Transfer','UPI','Cheque','Other')),
    status TEXT NOT NULL DEFAULT 'Pending'
        CHECK (status IN ('Pending','Paid','Failed','Refunded','Partially Refunded'))
);

CREATE TABLE IF NOT EXISTS return (
    return_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    so_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    return_date DATE NOT NULL DEFAULT CURRENT_DATE,
    quantity_returned INTEGER NOT NULL CHECK (quantity_returned > 0),
    reason TEXT NOT NULL,
    refund_amount NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (refund_amount >= 0),
    FOREIGN KEY (so_id, product_id) REFERENCES sales_order_item(so_id, product_id)
);

CREATE TABLE IF NOT EXISTS stock_transfer (
    transfer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES product(product_id),
    source_warehouse_id BIGINT NOT NULL REFERENCES warehouse(warehouse_id),
    destination_warehouse_id BIGINT NOT NULL REFERENCES warehouse(warehouse_id),
    employee_id BIGINT NOT NULL REFERENCES employee(employee_id),
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    transfer_date DATE NOT NULL DEFAULT CURRENT_DATE,
    CHECK (source_warehouse_id <> destination_warehouse_id)
);

CREATE INDEX IF NOT EXISTS idx_inventory_product ON inventory(product_id);
CREATE INDEX IF NOT EXISTS idx_po_supplier_date ON purchase_order(supplier_id, order_date);
CREATE INDEX IF NOT EXISTS idx_so_customer_date ON sales_order(customer_id, order_date);
CREATE INDEX IF NOT EXISTS idx_so_status ON sales_order(status);
CREATE INDEX IF NOT EXISTS idx_payment_so ON payment(so_id);
CREATE INDEX IF NOT EXISTS idx_transfer_date ON stock_transfer(transfer_date);

CREATE OR REPLACE VIEW low_stock AS
SELECT i.warehouse_id,
       w.name AS warehouse_name,
       i.product_id,
       p.product_name,
       i.quantity_on_hand,
       p.reorder_level,
       CASE WHEN i.quantity_on_hand = 0 THEN 'Out of stock' ELSE 'Reorder' END AS stock_class
FROM inventory i
JOIN warehouse w USING (warehouse_id)
JOIN product p USING (product_id)
WHERE i.quantity_on_hand <= p.reorder_level;

CREATE OR REPLACE FUNCTION apply_purchase_receipt()
RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.status = 'Received'
       AND (TG_OP = 'INSERT' OR OLD.status IS DISTINCT FROM 'Received') THEN
        IF NOT EXISTS (
            SELECT 1 FROM purchase_order_item WHERE po_id = NEW.po_id
        ) THEN
            RAISE EXCEPTION 'Add purchase order items before marking the order Received';
        END IF;

        INSERT INTO inventory (
            warehouse_id, product_id, quantity_on_hand, last_updated
        )
        SELECT NEW.warehouse_id, poi.product_id, poi.quantity_ordered, CURRENT_TIMESTAMP
        FROM purchase_order_item poi
        WHERE poi.po_id = NEW.po_id
        ON CONFLICT (warehouse_id, product_id) DO UPDATE
        SET quantity_on_hand = inventory.quantity_on_hand + EXCLUDED.quantity_on_hand,
            last_updated = CURRENT_TIMESTAMP;
    END IF;

    RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS trg_purchase_receipt_inventory ON purchase_order;
CREATE TRIGGER trg_purchase_receipt_inventory
AFTER INSERT OR UPDATE ON purchase_order
FOR EACH ROW EXECUTE FUNCTION apply_purchase_receipt();

CREATE OR REPLACE FUNCTION guard_completed_order_status()
RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF (TG_TABLE_NAME = 'purchase_order'
        AND OLD.status = 'Received'
        AND NEW.status <> 'Received')
       OR
       (TG_TABLE_NAME = 'sales_order'
        AND OLD.status = 'Delivered'
        AND NEW.status <> 'Delivered') THEN
        RAISE EXCEPTION 'Completed orders cannot be moved back to an earlier status';
    END IF;

    RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS trg_guard_purchase_status ON purchase_order;
CREATE TRIGGER trg_guard_purchase_status
BEFORE UPDATE OF status ON purchase_order
FOR EACH ROW EXECUTE FUNCTION guard_completed_order_status();

DROP TRIGGER IF EXISTS trg_guard_sales_status ON sales_order;
CREATE TRIGGER trg_guard_sales_status
BEFORE UPDATE OF status ON sales_order
FOR EACH ROW EXECUTE FUNCTION guard_completed_order_status();

CREATE OR REPLACE FUNCTION apply_sales_fulfilment()
RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    line RECORD;
BEGIN
    IF NEW.status = 'Delivered'
       AND (TG_OP = 'INSERT' OR OLD.status IS DISTINCT FROM 'Delivered') THEN
        IF NOT EXISTS (
            SELECT 1 FROM sales_order_item WHERE so_id = NEW.so_id
        ) THEN
            RAISE EXCEPTION 'Add sales order items before marking the order Delivered';
        END IF;

        FOR line IN
            SELECT product_id, quantity_ordered
            FROM sales_order_item
            WHERE so_id = NEW.so_id
        LOOP
            UPDATE inventory
            SET quantity_on_hand = quantity_on_hand - line.quantity_ordered,
                last_updated = CURRENT_TIMESTAMP
            WHERE warehouse_id = NEW.warehouse_id
              AND product_id = line.product_id
              AND quantity_on_hand >= line.quantity_ordered;

            IF NOT FOUND THEN
                RAISE EXCEPTION
                    'Insufficient inventory for product % in warehouse %',
                    line.product_id, NEW.warehouse_id;
            END IF;
        END LOOP;
    END IF;

    RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS trg_sales_fulfilment_inventory ON sales_order;
CREATE TRIGGER trg_sales_fulfilment_inventory
AFTER INSERT OR UPDATE ON sales_order
FOR EACH ROW EXECUTE FUNCTION apply_sales_fulfilment();

CREATE OR REPLACE FUNCTION apply_return_inventory()
RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    wh BIGINT;
BEGIN
    SELECT warehouse_id INTO wh
    FROM sales_order
    WHERE so_id = NEW.so_id;

    INSERT INTO inventory (
        warehouse_id, product_id, quantity_on_hand, last_updated
    )
    VALUES (wh, NEW.product_id, NEW.quantity_returned, CURRENT_TIMESTAMP)
    ON CONFLICT (warehouse_id, product_id) DO UPDATE
    SET quantity_on_hand = inventory.quantity_on_hand + EXCLUDED.quantity_on_hand,
        last_updated = CURRENT_TIMESTAMP;

    RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS trg_return_inventory ON return;
CREATE TRIGGER trg_return_inventory
AFTER INSERT ON return
FOR EACH ROW EXECUTE FUNCTION apply_return_inventory();

CREATE OR REPLACE FUNCTION apply_stock_transfer()
RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    UPDATE inventory
    SET quantity_on_hand = quantity_on_hand - NEW.quantity,
        last_updated = CURRENT_TIMESTAMP
    WHERE warehouse_id = NEW.source_warehouse_id
      AND product_id = NEW.product_id
      AND quantity_on_hand >= NEW.quantity;

    IF NOT FOUND THEN
        RAISE EXCEPTION
            'Insufficient inventory for product % in source warehouse %',
            NEW.product_id, NEW.source_warehouse_id;
    END IF;

    INSERT INTO inventory (
        warehouse_id, product_id, quantity_on_hand, last_updated
    )
    VALUES (
        NEW.destination_warehouse_id, NEW.product_id, NEW.quantity, CURRENT_TIMESTAMP
    )
    ON CONFLICT (warehouse_id, product_id) DO UPDATE
    SET quantity_on_hand = inventory.quantity_on_hand + EXCLUDED.quantity_on_hand,
        last_updated = CURRENT_TIMESTAMP;

    RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS trg_stock_transfer_inventory ON stock_transfer;
CREATE TRIGGER trg_stock_transfer_inventory
AFTER INSERT ON stock_transfer
FOR EACH ROW EXECUTE FUNCTION apply_stock_transfer();

CREATE OR REPLACE FUNCTION refresh_order_total()
RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    target_id BIGINT;
BEGIN
    IF TG_TABLE_NAME = 'purchase_order_item' THEN
        target_id := CASE WHEN TG_OP = 'DELETE' THEN OLD.po_id ELSE NEW.po_id END;
        UPDATE purchase_order
        SET total_amount = COALESCE(
            (SELECT SUM(quantity_ordered * unit_cost)
             FROM purchase_order_item WHERE po_id = target_id), 0
        )
        WHERE po_id = target_id;
    ELSE
        target_id := CASE WHEN TG_OP = 'DELETE' THEN OLD.so_id ELSE NEW.so_id END;
        UPDATE sales_order
        SET total_amount = COALESCE(
            (SELECT SUM(quantity_ordered * unit_price)
             FROM sales_order_item WHERE so_id = target_id), 0
        )
        WHERE so_id = target_id;
    END IF;

    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;

    RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS trg_purchase_order_total ON purchase_order_item;
CREATE TRIGGER trg_purchase_order_total
AFTER INSERT OR UPDATE OR DELETE ON purchase_order_item
FOR EACH ROW EXECUTE FUNCTION refresh_order_total();

DROP TRIGGER IF EXISTS trg_sales_order_total ON sales_order_item;
CREATE TRIGGER trg_sales_order_total
AFTER INSERT OR UPDATE OR DELETE ON sales_order_item
FOR EACH ROW EXECUTE FUNCTION refresh_order_total();

