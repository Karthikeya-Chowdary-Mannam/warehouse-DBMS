-- Add the new unique constraints to an existing database, if not present.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'uq_product_name'
          AND conrelid = 'product'::regclass
    ) THEN
        ALTER TABLE product
            ADD CONSTRAINT uq_product_name UNIQUE (product_name);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'uq_supplier_name'
          AND conrelid = 'supplier'::regclass
    ) THEN
        ALTER TABLE supplier
            ADD CONSTRAINT uq_supplier_name UNIQUE (name);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'uq_customer_name'
          AND conrelid = 'customer'::regclass
    ) THEN
        ALTER TABLE customer
            ADD CONSTRAINT uq_customer_name UNIQUE (name);
    END IF;
END $$;
